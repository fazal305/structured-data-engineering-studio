const studio = window.StructuredStudio;

studio.initSharedPage("api-doc-generator");

let currentDocs = [];

document.addEventListener("DOMContentLoaded", () => {
    loadDocsSample();

    document.querySelector("#loadDocsSampleBtn").addEventListener("click", loadDocsSample);
    document.querySelector("#generateDocsBtn").addEventListener("click", generateDocsFromInput);
    document.querySelector("#copyMarkdownBtn").addEventListener("click", copyMarkdownDocs);
    document.querySelector("#downloadMarkdownBtn").addEventListener("click", downloadMarkdownDocs);
});

function generateDocsFromInput() {
    const text = document.querySelector("#docsJsonInput").value.trim();
    const parsed = studio.parseJson(text);

    if (!parsed.ok) {
        studio.showStatus(`JSON error: ${parsed.error}`, "danger");
        return;
    }

    currentDocs = analyzeJsonResponse(parsed.data);
    renderDocumentation(currentDocs);

    const markdown = generateMarkdownDocs(currentDocs);
    document.querySelector("#markdownOutput").textContent = markdown;

    const workspace = studio.loadWorkspace();
    workspace.generatedDocs.unshift({
        id: studio.generateId("docs"),
        name: "Generated API Docs",
        createdAt: new Date().toISOString(),
        docs: currentDocs
    });
    workspace.generatedDocs = workspace.generatedDocs.slice(0, 12);
    studio.saveWorkspace(workspace);

    studio.addActivityLog("API Docs Generator", "Documentation generated", `${currentDocs.length} fields documented.`);
    studio.showStatus("API documentation generated.", "success");
}

function analyzeJsonResponse(data) {
    const sample = Array.isArray(data) ? data[0] : data;
    return generateFieldDocs(sample, "");
}

function generateFieldDocs(value, path = "") {
    const docs = [];

    if (Array.isArray(value)) {
        docs.push({
            path: path || "root",
            type: "array",
            description: `Array field containing ${value.length} item(s).`,
            example: value[0] ?? []
        });

        if (value[0] && typeof value[0] === "object") {
            docs.push(...generateFieldDocs(value[0], `${path}[]`));
        }

        return docs;
    }

    if (value && typeof value === "object") {
        if (path) {
            docs.push({
                path,
                type: "object",
                description: "Nested object field.",
                example: value
            });
        }

        Object.entries(value).forEach(([key, childValue]) => {
            const nextPath = path ? `${path}.${key}` : key;
            docs.push(...generateFieldDocs(childValue, nextPath));
        });

        return docs;
    }

    docs.push({
        path: path || "root",
        type: studio.getValueType(value),
        description: createDescription(path, value),
        example: value
    });

    return docs;
}

function createDescription(path, value) {
    const fieldName = String(path).split(".").pop() || "value";
    const type = studio.getValueType(value);

    if (type === "string") {
        return `${fieldName} is a text field.`;
    }

    if (type === "number") {
        return `${fieldName} is a numeric field.`;
    }

    if (type === "boolean") {
        return `${fieldName} is a true/false field.`;
    }

    if (type === "null") {
        return `${fieldName} currently has a null value.`;
    }

    return `${fieldName} field.`;
}

function renderDocumentation(docs) {
    const target = document.querySelector("#documentationOutput");

    if (!docs.length) {
        target.innerHTML = studio.renderEmptyState("No fields detected.");
        return;
    }

    const typeSummary = docs.reduce((summary, doc) => {
        summary[doc.type] = (summary[doc.type] || 0) + 1;
        return summary;
    }, {});

    target.innerHTML = `
    <div class="grid grid-3 mb-3">
      ${Object.entries(typeSummary)
            .map(
                ([type, count]) => `
            <div class="metric-card">
              <div class="metric-value">${count}</div>
              <div class="metric-label">${studio.escapeHtml(type)} fields</div>
            </div>
          `
            )
            .join("")}
    </div>

    ${docs
            .map(
                (doc) => `
          <div class="field-doc">
            <div class="field-path">${studio.escapeHtml(doc.path)}</div>
            <span class="type-chip">${studio.escapeHtml(doc.type)}</span>
            <p class="mt-2 mb-1">${studio.escapeHtml(doc.description)}</p>
            <small>Example: ${studio.escapeHtml(JSON.stringify(doc.example))}</small>
          </div>
        `
            )
            .join("")}
  `;
}

function generateMarkdownDocs(docs) {
    const lines = [
        "# API Response Documentation",
        "",
        "Generated by Structured Data Engineering Studio.",
        "",
        "## Type Summary",
        ""
    ];

    const typeSummary = docs.reduce((summary, doc) => {
        summary[doc.type] = (summary[doc.type] || 0) + 1;
        return summary;
    }, {});

    Object.entries(typeSummary).forEach(([type, count]) => {
        lines.push(`- **${type}**: ${count}`);
    });

    lines.push("", "## Fields", "");

    docs.forEach((doc) => {
        lines.push(`### \`${doc.path}\``);
        lines.push("");
        lines.push(`- Type: \`${doc.type}\``);
        lines.push(`- Description: ${doc.description}`);
        lines.push(`- Example: \`${JSON.stringify(doc.example)}\``);
        lines.push("");
    });

    return lines.join("\n");
}

function copyMarkdownDocs() {
    studio.copyText(document.querySelector("#markdownOutput").textContent, "Markdown docs copied.");
}

function downloadMarkdownDocs() {
    studio.downloadTextFile("api-documentation.md", document.querySelector("#markdownOutput").textContent);
}

function loadDocsSample() {
    const sample = {
        user: {
            id: 101,
            name: "Fazal Abbas",
            email: "fazal@example.com",
            active: true,
            skills: ["HTML", "CSS", "JavaScript", "APIs"],
            profile: {
                city: "Karachi",
                role: "Frontend Developer"
            }
        },
        meta: {
            requestId: "REQ-2026-001",
            status: "success"
        }
    };

    document.querySelector("#docsJsonInput").value = studio.formatJson(sample);
    generateDocsFromInput();
}